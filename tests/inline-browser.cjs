const {chromium}=require('./playwright.cjs');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1674,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.READMASTER_URL||'http://127.0.0.1:8766',id='f285b0971ae4a790e402fb93';
 let source,sentenceId;
 await page.route('**/api/document/'+id,async route=>{
  const response=await route.fetch(),doc=await response.json();
  doc.processing_progress={state:'processing',percent:42,total_units:392,done_units:165,page:3,phase:'evaluate',model:'Codex 默认模型',eta_seconds:720};doc.state='processing';
  const sample=doc.blocks.filter(b=>Object.keys(b.translations).length).flatMap(b=>b.sentences).find(s=>s.source.length>150);
  source=sample.source;sentenceId=sample.id;
  await route.fulfill({response,json:doc});
 });
 await page.goto(base);await page.locator('#startupSplash').waitFor({state:'hidden'});await page.locator('#fileInput').setInputFiles(process.env.READMASTER_TEST_PDF||'tests/paper_sets/2210.03629v3.pdf');
 await page.locator('.sentence').first().waitFor();
 const sentence=page.locator(`.sentence[data-sentence="${sentenceId}"]`);await sentence.scrollIntoViewIfNeeded();
 const text=await sentence.textContent(),block=sentence.locator('..'),before=await block.boundingBox();
 await sentence.hover();await page.waitForTimeout(150);
 if(await sentence.textContent()!==text)throw Error('hover must not change language');
 await sentence.click();
 if(await sentence.textContent()!==source)throw Error('click did not replace Chinese in place');
 const other=page.locator('.sentence').first(),otherText=await other.textContent();
 await other.click();if(await sentence.textContent()!==source)throw Error('sentences must toggle independently');
 await other.click();if(await other.textContent()!==otherText)throw Error('other sentence did not restore');
 if(await page.locator('.source-popup').count())throw Error('popup remains');
 const after=await block.boundingBox();if(JSON.stringify(before)!==JSON.stringify(after))throw Error('paragraph frame moved');
 fs.mkdirSync('.impeccable/review/inline',{recursive:true});
 await page.locator('.page-image').first().evaluate(img=>img.complete?Promise.resolve():new Promise(r=>img.onload=r));
 await page.screenshot({path:'.impeccable/review/inline/desktop.png'});
 await page.mouse.move(20,70);if(await sentence.textContent()!==source)throw Error('leave must retain English');
 await sentence.click();if(await sentence.textContent()!==text)throw Error('second click did not restore');
 await sentence.focus();if(await sentence.textContent()!==text)throw Error('focus must not change language');
 await page.keyboard.press('Enter');if(await sentence.textContent()!==source)throw Error('Enter did not toggle');
 await page.keyboard.press('Space');if(await sentence.textContent()!==text)throw Error('Space did not toggle');
 await sentence.click();await page.locator('#zoom').selectOption('1');await page.waitForTimeout(250);
 if(await sentence.textContent()!==source)throw Error('zoom lost selected language');
 await sentence.focus();await page.keyboard.press('Escape');if(await sentence.textContent()!==text)throw Error('Escape did not restore');
 await page.locator('#originalButton').click();if(await page.locator('.sentence').count())throw Error('original mode broken');
 await page.locator('#chineseButton').click();
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(400);
 await page.locator('#translationProgress').scrollIntoViewIfNeeded();
 await page.screenshot({path:'.impeccable/review/inline/mobile.png'});
 await page.locator('#libraryButton').click();if(await page.locator('.sentence').count())throw Error('library reset failed');
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({clickToggle:true,hoverUnchanged:true,leaveUnchanged:true,keyboard:true,zoomPreserved:true,paragraphAnchored:true,popupRemoved:true,mobile:true,errors}));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
